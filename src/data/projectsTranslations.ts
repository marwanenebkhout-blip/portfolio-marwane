export function localizeProject(project: Project, lang: 'fr' | 'en'): Project {
  if (lang === 'fr') return project;
  const translation = projectsTranslationsEn[project.id];
  if (!translation) return project;

  return {
    ...project,
    subtitle: translation.subtitle || project.subtitle,
    summary: translation.summary || project.summary,
    description: translation.description || project.description,
    tags: translation.tags || project.tags,
    role: translation.role || project.role,
    metrics: translation.metrics || project.metrics,
    deliverables: translation.deliverables || project.deliverables,
    videoCaption: translation.videoCaption || project.videoCaption,
  };
}
